// Minimal i18n: English text is the key, Polish is a dictionary. Missing keys fall back to English.

export type Lang = "en" | "pl";
export type LangSetting = "system" | Lang;

let current: Lang = "en";

export function resolveLang(setting: LangSetting | undefined): Lang {
  if (setting === "en" || setting === "pl") return setting;
  return (navigator.language || "en").toLowerCase().startsWith("pl") ? "pl" : "en";
}

export function setLang(l: Lang) {
  current = l;
  document.documentElement.lang = l;
}

export function lang(): Lang {
  return current;
}

/** Translate `key`, replacing `{name}` placeholders. */
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = current === "pl" ? (PL[key] ?? key) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Plural helper: one / few (2-4) / many, Polish rules; English uses one/many. */
export function plural(n: number, one: string, few: string, many: string): string {
  if (current !== "pl") return n === 1 ? one : many;
  const m10 = n % 10;
  const m100 = n % 100;
  if (n === 1) return one;
  if (m10 >= 2 && m10 <= 4 && !(m100 >= 12 && m100 <= 14)) return few;
  return many;
}

/** Messages produced by the Rust backend (errors, notes, warnings) → translated text. */
const PATTERNS: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^Unsupported or damaged image file(?:: (.*))?$/, (m) => (m[1] ? `${t("Unsupported or damaged image file")}: ${tr(m[1])}` : t("Unsupported or damaged image file"))],
  [/^Image is too large \((\d+) × (\d+) px\)\. The limit is (\d+) megapixels\.$/, (m) => t("Image is too large ({w} × {h} px). The limit is {mp} megapixels.", { w: m[1], h: m[2], mp: m[3] })],
  [/^Not enough disk space: (\d+) MB needed, (\d+) MB free on the target drive$/, (m) => t("Not enough disk space: {a} MB needed, {b} MB free on the target drive", { a: m[1], b: m[2] })],
  [/^Model "(.*)" is not installed$/, (m) => t("Model “{m}” is not installed", { m: m[1] })],
  [/^No internet connection or the server is unreachable \((.*)\)$/, (m) => t("No internet connection or the server is unreachable ({e})", { e: m[1] })],
  [/^File verification failed for (.*) \(checksum mismatch\)\. The download was discarded\.$/, (m) => t("File verification failed for {f} (checksum mismatch). The download was discarded.", { f: m[1] })],
  [/^Download failed: (.*)$/, (m) => `${t("Download failed")}: ${m[1]}`],
  [/^Out of GPU memory while running (.*)$/, (m) => t("Out of GPU memory while running {m}", { m: m[1] })],
  [/^Invalid settings: (.*)$/, (m) => `${t("Invalid settings")}: ${tr(m[1])}`],
  [/^Upscaling would create a (\d+) × (\d+) px image \((\d+) MP\), above the 160 MP limit\. Resize the image first or use 2×\.$/, (m) => t("Upscaling would create a {w} × {h} px image ({mp} MP), above the 160 MP limit. Resize the image first or use 2×.", { w: m[1], h: m[2], mp: m[3] })],
  [/^JPG does not support transparency\. Transparent areas will be filled with (#[0-9A-F]{6})\. Use PNG, WebP or AVIF to keep them\.$/, (m) => t("JPG does not support transparency. Transparent areas will be filled with {c}. Use PNG, WebP or AVIF to keep them.", { c: m[1] })],
  [/^(.*) needs about (\d+) GB of VRAM; this GPU has ([\d.]+) GB, so it runs on the CPU\.$/, (m) => t("{n} needs about {a} GB of VRAM; this GPU has {b} GB, so it runs on the CPU.", { n: t(m[1]), a: m[2], b: m[3] })],
  [/^Cannot access (.*): (.*)$/, (m) => t("Cannot access {p}: {e}", { p: m[1], e: m[2] })],
  [/^Could not encode (.*?): (.*)$/, (m) => t("Could not encode {f}: {e}", { f: m[1], e: m[2] })],
];

/** Translate a backend message (exact dictionary match first, then known patterns). */
export function tr(msg: string | null | undefined): string {
  if (!msg) return "";
  if (current !== "pl") return msg;
  if (PL[msg]) return PL[msg];
  for (const [re, f] of PATTERNS) {
    const m = msg.match(re);
    if (m) return f(m);
  }
  return msg;
}

